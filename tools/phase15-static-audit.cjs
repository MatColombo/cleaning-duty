const { readFileSync, existsSync } = require('node:fs')
const { join } = require('node:path')
const root = join(__dirname, '..')
const read = p => readFileSync(join(root,p), 'utf8')
const pkg = JSON.parse(read('package.json'))
const manifest = JSON.parse(read('public/manifest.webmanifest'))
const sw = read('public/sw.js')
const fail = [], note = []
function check(ok, message) { if (!ok) fail.push(message); else note.push(`PASS ${message}`) }
check(pkg.version.startsWith('2.0.0-rc.'),'Release identity remains a V2 candidate until full browser/build gates pass')
check(read('README.md').startsWith(`# House Care PWA — v${pkg.version}`),'README identifies the current candidate')
check(sw.includes(`const VERSION = 'v${pkg.version}'`),'SW version matches package')
check(sw.includes('retro-assets-v2-rc1'),'SW cache asset revision bumped')
check(manifest.icons.every(icon => icon.src.endsWith(`?v=${pkg.version}`)),'Installed icons are versioned')
check(manifest.icons.every(icon => existsSync(join(root,'public',icon.src.slice(1).split('?')[0]))),'Installed icon assets exist')
check(sw.includes('SKIP_WAITING') && sw.includes('notificationclick'),'SW retains update and notification handling')
check(!existsSync(join(root,'src/pages/TodayPage.tsx')),'Orphan V1 Today page removed')
check(!existsSync(join(root,'src/components/Illustration.tsx')),'Legacy mask-only illustration component removed')
check(!existsSync(join(root,'public/illustrations')),'Orphan V1 illustrations retired')
check(!read('src/components/AppShell.tsx').includes('bottom-nav'),'App Shell has no bottom nav')
const routes = read('src/App.tsx')
for (const route of ['timeline','home','routines','actions','supplies','analysis','settings','task/:taskId']) check(routes.includes(`path="${route}"`),`Active route ${route}`)
check(routes.includes('LegacyRouteRedirect'),'Legacy route resolver preserved')
check(read('src/components/overview/CardArtwork.tsx').includes('aria-hidden="true"'),'Decorative Care Card SVG hidden from screen readers')
check(read('src/components/overview/ActiveDeck.tsx').includes('v2-deck-back'),'Deck rear cards are lightweight CSS layers')
check(!read('src/visual/procedural/render-card.ts').includes('feTurbulence'),'No card-level turbulence')
check(!/Math\.random\s*\(/.test(read('src/visual/procedural/recipe.ts').replace(/\/\*[\s\S]*?\*\//g, '')), 'Deterministic card recipe')
check(read('src/styles/overview-v2.css').includes('data-v2-no-art'),'No-art presentation fallback')
check(read('src/styles/overview-v2.css').includes('prefers-reduced-motion'),'Reduced-motion presentation safeguard')
const tokens = read('src/styles/tokens.css'), legacy = read('src/styles.css')
check((tokens.match(/:root\s*\{/g) || []).length === 1, 'One canonical CSS root-token fallback block')
check(!/:root\s*\{/.test(legacy),'Legacy CSS no longer contains duplicate root token generations')
check(Buffer.byteLength(legacy)<85000,'Legacy CSS materially reduced')
check(existsSync(join(root,'tests/fixtures/pre-v2-household-backup.json')),'Pre-V2 backup fixture retained')
for (const status of note) console.log(status)
if (fail.length) { fail.forEach(f => console.error(`FAIL ${f}`)); process.exitCode = 1 }
else console.log(`Release source/asset audit passed (${note.length} checks); browser/build/device gates remain separate.`)
