/** Phase 17B domain-independent deck motion tests. These do not simulate browser pointer dispatch. */
declare const require: (name: string) => any
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
import { boundedDrag, dragTransform, gestureAxis, releaseDirection, survivingDeckId } from '../src/lib/deckGestures'
import { nextDeckIndex } from '../src/lib/overviewDeck'
import { translate } from '../src/lib/translations'

assert.equal(gestureAxis(3, 4), 'undecided')
assert.equal(gestureAxis(60, 8), 'horizontal', 'horizontal touch is classified as a swipe')
assert.equal(gestureAxis(-70, 11), 'horizontal', 'left mouse drag is a swipe')
assert.equal(gestureAxis(10, 90), 'vertical', 'vertical card-details scroll remains scrollable')
assert.equal(gestureAxis(15, 14), 'undecided', 'diagonal ambiguous pointer waits for a clear axis')
for (const dx of [-1e6, -400, -90, 0, 90, 400, 1e6]) {
  const {x,y,angle,progress} = boundedDrag(dx, 10000, 390)
  assert.ok(Math.abs(x) <= 220 && Math.abs(y) <= 22 && Math.abs(angle) <= 7 && Math.abs(progress) <= 1)
  assert.ok(!dragTransform(x,y,angle).includes('NaN'))
}
assert.equal(releaseDirection(-140, 0, 390, 4),1,'left drag = next')
assert.equal(releaseDirection(140, 0, 390, 4),-1,'right drag = previous')
assert.equal(releaseDirection(-26,-.85,390,4),1,'fast, short left flick with inertia = next')
assert.equal(releaseDirection(26,.85,390,4),-1,'fast, short right flick with inertia = previous')
assert.equal(releaseDirection(18,3,390,4),0,'a tiny extremely fast jitter cannot turn the deck')
assert.equal(releaseDirection(28,0,390,4),0,'a slow short move returns to start')
assert.equal(releaseDirection(-200,-1,390,1),0,'a single card does not navigate')
assert.equal(releaseDirection(Number.NaN,.5,390,4),0,'invalid event samples cannot navigate')
assert.equal(nextDeckIndex(4,0,-1),3,'previous wraps')
assert.equal(nextDeckIndex(4,3,1),0,'next wraps')
assert.equal(survivingDeckId(['a','b','c'],['c','a','b'],'b'),'b','same card retained after reorder')
assert.equal(survivingDeckId(['a','b','c'],['a','c'],'b'),'c','removed card selects next surviving neighbor')
assert.equal(survivingDeckId(['a','b','c'],['a'],'c'),'a','removed last card falls back to predecessor')
assert.equal(survivingDeckId(['a'],[], 'a'),null)
const deck = readFileSync('src/components/overview/ActiveDeck.tsx','utf8')
const css = readFileSync('src/styles/overview-v2.css','utf8')
const card = readFileSync('src/components/overview/CareCard.tsx','utf8')
assert.ok(deck.includes('onPointerDown={pointerDown}') && deck.includes('onPointerMove={pointerMove}') && deck.includes('onPointerCancel={event => endPointer(event, true)}'))
assert.ok(deck.includes('onLostPointerCapture={event => endPointer(event, true)}'))
assert.ok(deck.includes('setPointerCapture') && deck.includes('releasePointerCapture'))
assert.ok(deck.includes('onClickCapture={clickCapture}') && deck.includes('event.stopPropagation()'), 'drag suppresses generated clicks')
assert.ok(deck.includes('INTERACTIVE') && deck.includes('.closest(INTERACTIVE)'), 'interactive descendants never begin a gesture')
assert.ok(translate('en','deckBrowseHint').includes('never completes') && translate('it','deckBrowseHint').includes('non completa'))
assert.ok(deck.includes('aria-describedby="v2-deck-browse-help"'))
assert.ok(deck.includes('aria-label={t(\'previousCard\')}') && deck.includes('aria-label={t(\'nextCard\')}'))
assert.ok(deck.includes("event.key === 'ArrowLeft'") && deck.includes("event.key === 'ArrowRight'"))
assert.ok(deck.includes("prefers-reduced-motion: reduce") && css.includes('.v2-deck-front, .v2-deck-back { animation: none !important'))
assert.ok(css.includes('touch-action: pan-y') && css.includes('.v2-deck-front') && css.includes('.v2-deck-back'))
assert.ok(!deck.includes('completeTask(') && !deck.includes('skipTask(') && !deck.includes('supabase'), 'navigation must not mutate task or call backend')
assert.ok(card.includes('onComplete(task.id)') && card.includes('onMore(task.id)'), 'explicit task actions unchanged')
assert.equal((deck.match(/<CareCard /g) ?? []).length,1,'only one front card / heavy SVG rendered')
assert.equal((deck.match(/<div className="v2-deck-back/g) ?? []).length,2,'rear cards remain cheap CSS elements')
console.log('Phase 17B gesture direction, velocity, bound, identity, cancellation, action isolation, reduced motion, keyboard and rear-card contract tests passed')
